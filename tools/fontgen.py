"""fontgen.py: draw fonts/en_font.txt into the game fonts (FILEDATA 506 and 509) and give the VWF advances.

English glyphs take the kana cells (unused once the text is English): ASCII 0x20-0x7E -> code 0x10 + (c - 0x20),
'…' -> 0x6F. Fill pixel 1, outline 0xF (8-neighbour ring), placed at cell row 2 / column 1.

    python -X utf8 tools/fontgen.py --tbl    # rewrite tbl/en.tbl from this mapping
"""
import sys
from pathlib import Path

import numpy as np

import font

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "fonts/en_font.txt"
FONTS = (506, 509)
TOP, LEFT, FILL, OUTLINE = 2, 1, 1, 0xF
SPACE = 3
CTRL = ["FDFF={end}", "FFFF={n}", "FEFF={p}", "F4FF={sp}", "F5FF={var}", "F6FF={f6}", "F7FF={c1}", "F8FF={c2}",
        "F9FF={f9}", "FCFF={/c}", "0001=♥", "0101={icon1}", "0201={icon2}", "0301={icon3}", "0600=•"]


def code_of(ch):
    return 0x6F if ch == "…" else 0x10 + ord(ch) - 0x20


def glyphs(art=ART):
    out, cur = {}, None
    for line in art.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") and cur is None or not line.strip():
            continue
        if line.startswith("== "):
            cur = line[3:]
            out[cur] = []
        else:
            out[cur].append(line)
    for ch, rows in out.items():
        assert len(rows) == 11 and len({len(r) for r in rows}) == 1, f"glyph {ch!r}: 11 equal rows needed"
    return out


def cell(rows):
    g = np.zeros((16, 16), np.uint8)
    fill = np.array([[c == "#" for c in r] for r in rows], bool)
    h, w = fill.shape
    m = np.zeros((16, 16), bool)
    m[TOP:TOP + h, LEFT:LEFT + w] = fill
    ring = np.zeros_like(m)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            ring |= np.roll(np.roll(m, dy, 0), dx, 1)
    g[ring & ~m] = OUTLINE
    g[m] = FILL
    return g, w


def put_cell(rgcn, code, g):
    """Inverse of font.glyph: write a 16x16 cell of 4-bit pixels."""
    d = bytearray(rgcn)
    gr, gc = divmod(code, 16)
    for ty in range(2):
        for tx in range(2):
            t = (gr * 2 + ty) * font.COLS_TILES + gc * 2 + tx
            px = g[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8].astype(np.uint8)
            d[font.HDR + t * 32:font.HDR + t * 32 + 32] = (px[:, 0::2] | (px[:, 1::2] << 4)).tobytes()
    return bytes(d)


def apply(rgcn):
    """-> (new rgcn, {code: advance})"""
    adv = {code_of(" "): SPACE}
    rgcn = put_cell(rgcn, code_of(" "), np.zeros((16, 16), np.uint8))
    for ch, rows in glyphs().items():
        g, w = cell(rows)
        rgcn = put_cell(rgcn, code_of(ch), g)
        adv[code_of(ch)] = w + 1
    return rgcn, adv


def table_lines():
    lines = ["# English table: generated by tools/fontgen.py --tbl from fonts/en_font.txt. Do not edit by hand."] + CTRL
    lines.append(f"{code_of(' '):02X}00=\\s")
    for ch in glyphs():
        lines.append(f"{code_of(ch):02X}00={ch}")
    return lines


if __name__ == "__main__":
    if sys.argv[1:] == ["--tbl"]:
        (ROOT / "tbl/en.tbl").write_text("\n".join(table_lines()) + "\n", encoding="utf-8", newline="\n")
    else:
        sys.exit(__doc__)
